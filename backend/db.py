def dump_all_tables(conn: Connection) -> dict[str, list[dict[str, Any]]]:
    """Every table as a list of plain dicts, for `outbound backup`."""
    out: dict[str, list[dict[str, Any]]] = {}
    for table in TABLES:
        if not _table_exists(conn, table):
            out[table] = []
            continue
        rows = conn.execute(f"SELECT * FROM {table} ORDER BY 1").fetchall()
        out[table] = [{key: _jsonable(value) for key, value in dict(row).items()} for row in rows]
    return out


def _jsonable(value: Any) -> Any:
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return str(value)
