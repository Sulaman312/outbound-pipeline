class Result:
    """Thin wrapper so callers can use fetchone/fetchall/rowcount like sqlite3."""

    def __init__(self, result: CursorResult[Any]) -> None:
        self._result = result

    def fetchone(self) -> RowMapping | None:
        row = self._result.mappings().fetchone()
        return row

    def fetchall(self) -> list[RowMapping]:
        return list(self._result.mappings().fetchall())

    @property
    def rowcount(self) -> int:
        return self._result.rowcount or 0


class Connection:
    """SQLAlchemy connection with sqlite3-style `with conn:` transactions.

    Statements run inside a transaction that SQLAlchemy starts on its own. The outermost
    `with conn:` block commits it on success and rolls it back on an error. A block inside
    another block doesn't commit early: the outer one decides.
    """

    def __init__(self, sa_conn: SaConnection, url: str) -> None:
        self._conn = sa_conn
        self.url = url
        self._depth = 0

    @property
    def dialect(self) -> str:
        return self._conn.dialect.name

    def execute(self, sql: str, params: dict[str, Any] | None = None) -> Result:
        return Result(self._conn.execute(text(sql), params or {}))

    def executemany(self, sql: str, params_list: list[dict[str, Any]]) -> None:
        if params_list:
            self._conn.execute(text(sql), params_list)

    def __enter__(self) -> Connection:
        self._depth += 1
        return self

    def __exit__(self, exc_type: type[BaseException] | None, *_: object) -> None:
        self._depth -= 1
        if self._depth:
            return
        if exc_type is None:
            self._conn.commit()
        else:
            self._conn.rollback()

    def close(self) -> None:
        self._conn.close()


_engines: dict[str, Engine] = {}


def _normalize_url(url: str) -> str:
    """Use the psycopg 3 driver for Postgres URLs."""
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://") :]
    if url.startswith("postgresql://") and "+psycopg" not in url.split("://", 1)[0]:
        url = "postgresql+psycopg://" + url[len("postgresql://") :]
    return url


def database_url(root: Path) -> str:
    """DATABASE_URL from the environment, or sqlite under the project data folder."""
    url = os.environ.get("DATABASE_URL", "").strip()
    if url:
        return _normalize_url(url)
    path = (root / "data" / "outbound.db").resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    return f"sqlite:///{path.as_posix()}"


def describe_database(url: str, root: Path | None = None) -> str:
    """Human label for `outbound check`. Never includes the password."""
    if url.startswith("sqlite:///"):
        path = Path(url.removeprefix("sqlite:///"))
        if root is not None:
            try:
                return f"sqlite at {path.relative_to(root).as_posix()}"
            except ValueError:
                pass
        return f"sqlite at {path.as_posix()}"
    host = urlparse(url).hostname or "unknown"
    return f"postgres at {host}"


def connect(root: Path, *, url: str | None = None) -> Connection:
    """Open the database and make sure tables exist."""
    resolved = _normalize_url(url) if url else database_url(root)
    if resolved.startswith("sqlite:///"):
        Path(resolved.removeprefix("sqlite:///")).parent.mkdir(parents=True, exist_ok=True)
    if resolved not in _engines:
        # pre-ping: the app keeps connections in a pool for hours, and Supabase may close an
        # idle one. A quick check on checkout replaces it instead of failing the request.
        _engines[resolved] = create_engine(resolved, pool_pre_ping=True)
    sa_conn = _engines[resolved].connect()
    conn = Connection(sa_conn, resolved)
    with conn:
        init_schema(conn)
    return conn


def init_schema(conn: Connection) -> None:
    """Create a new database, or refuse one from newer code."""
    version = _read_schema_version(conn)
    if version > SCHEMA_VERSION:
        raise RuntimeError(
            f"database schema is version {version}, this code knows {SCHEMA_VERSION}. Update the code."
        )
    if version == 0:
        for statement in _schema_statements(conn.dialect):
            conn.execute(statement)
        conn.execute("INSERT INTO schema_version (version) VALUES (:version)", {"version": 1})
        version = 1
    if conn.dialect == "postgresql":
        _enable_rls(conn)
    # Future versions: run migrations here, then UPDATE schema_version.


def _read_schema_version(conn: Connection) -> int:
    if not _table_exists(conn, "schema_version"):
        return 0
    row = conn.execute("SELECT version FROM schema_version").fetchone()
    return int(row["version"]) if row else 0


def _table_exists(conn: Connection, name: str) -> bool:
    if conn.dialect == "postgresql":
        row = conn.execute(
            "SELECT 1 FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_name = :name",
            {"name": name},
        ).fetchone()
    else:
        row = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = :name",
            {"name": name},
        ).fetchone()
    return row is not None


def _enable_rls(conn: Connection) -> None:
    """Block Supabase's public API key on every table; we connect as the owner so we still see rows.

    Checks first, so a normal connect costs one query and only fixes tables that need it.
    """
    rows = conn.execute(
        "SELECT relname FROM pg_class "
        "WHERE relnamespace = 'public'::regnamespace AND relkind = 'r' AND NOT relrowsecurity"
    ).fetchall()
    for name in (str(row["relname"]) for row in rows):
        if name in TABLES:
            conn.execute(f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY")


def now_utc() -> str:
    """Current UTC time, like 2026-10-15T09:30:00Z."""
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def current_month() -> str:
    """Current UTC month, like 2026-10."""
    return datetime.now(UTC).strftime("%Y-%m")


# --- usage --------------------------------------------------------------------------------------


def usage_this_month(conn: Connection, provider: str, unit: str) -> int:
    row = conn.execute(
        "SELECT amount FROM usage WHERE provider = :provider AND unit = :unit AND month = :month",
        {"provider": provider, "unit": unit, "month": current_month()},
    ).fetchone()
    return int(row["amount"]) if row else 0


def add_usage(conn: Connection, provider: str, unit: str, amount: int) -> None:
    conn.execute(
        """
        INSERT INTO usage (provider, unit, month, amount)
        VALUES (:provider, :unit, :month, :amount)
        ON CONFLICT (provider, unit, month) DO UPDATE SET amount = usage.amount + excluded.amount
        """,
        {"provider": provider, "unit": unit, "month": current_month(), "amount": amount},
    )


def reserve_usage(conn: Connection, provider: str, unit: str, amount: int, cap: int) -> bool:
    """Reserve `amount` under the monthly cap in one statement. False if it would go over.

    A reservation is never released, so a failed API call still counts against the cap.
    """
    month = current_month()
    conn.execute(
        """
        INSERT INTO usage (provider, unit, month, amount)
        VALUES (:provider, :unit, :month, 0)
        ON CONFLICT (provider, unit, month) DO NOTHING
        """,
        {"provider": provider, "unit": unit, "month": month},
    )
    row = conn.execute(
        """
        UPDATE usage
        SET amount = amount + :amount
        WHERE provider = :provider AND unit = :unit AND month = :month
          AND amount + :amount <= :cap
        RETURNING amount
        """,
        {
            "provider": provider,
            "unit": unit,
            "month": month,
            "amount": amount,
            "cap": cap,
        },
    ).fetchone()
    return row is not None


# --- companies ----------------------------------------------------------------------------------


def insert_company(conn: Connection, company: dict[str, Any]) -> bool:
    """Save a company. Returns False if we already have its domain or provider id."""
    params = {column: company.get(column) for column in COMPANY_COLUMNS}
    params["created_at"] = now_utc()
    placeholders = ", ".join(f":{c}" for c in (*COMPANY_COLUMNS, "created_at"))
    result = conn.execute(
        f"""
        INSERT INTO companies ({", ".join((*COMPANY_COLUMNS, "created_at"))})
        VALUES ({placeholders})
        ON CONFLICT DO NOTHING
        """,
        params,
    )
    return result.rowcount == 1


def list_companies(
    conn: Connection, segment: str | None = None, search: str | None = None
) -> list[RowMapping]:
    """Saved companies, oldest first, leaving out any domain on the do-not-contact list.

    `search` keeps companies whose name or domain contains that text (any case).
    """
    sql = "SELECT * FROM companies WHERE domain NOT IN (SELECT value FROM suppression)"
    params: dict[str, Any] = {}
    if segment:
        sql += " AND segment = :segment"
        params["segment"] = segment
    if search and search.strip():
        sql += " AND (LOWER(name) LIKE :search OR LOWER(domain) LIKE :search)"
        params["search"] = f"%{search.strip().lower()}%"
    return conn.execute(sql + " ORDER BY id", params).fetchall()


def raw_records(conn: Connection, segment: str | None = None) -> list[str]:
    """The provider's original JSON for each saved company."""
    sql = "SELECT raw FROM companies WHERE raw IS NOT NULL"
    params: dict[str, Any] = {}
    if segment:
        sql += " AND segment = :segment"
        params["segment"] = segment
    return [str(row["raw"]) for row in conn.execute(sql + " ORDER BY id", params).fetchall()]


def count_companies(conn: Connection) -> dict[str, int]:
    """Number of saved companies per segment."""
    rows = conn.execute("SELECT segment, COUNT(*) AS n FROM companies GROUP BY segment").fetchall()
    return {str(row["segment"]): int(row["n"]) for row in rows}


def count_companies_by_status(conn: Connection) -> dict[str, int]:
    """Number of saved companies per status (new, exported, enriched, no_contact)."""
    rows = conn.execute("SELECT status, COUNT(*) AS n FROM companies GROUP BY status").fetchall()
    return {str(row["status"]): int(row["n"]) for row in rows}


# --- suppression --------------------------------------------------------------------------------


def is_suppressed(conn: Connection, value: str) -> bool:
    row = conn.execute(
        "SELECT 1 AS one FROM suppression WHERE value = :value", {"value": value}
    ).fetchone()
    return row is not None


def add_suppression(conn: Connection, value: str, kind: str, reason: str) -> bool:
    """Add an entry. Returns False if it was already there. Entries are never removed."""
    result = conn.execute(
        "INSERT INTO suppression (value, kind, reason, added_at) "
        "VALUES (:value, :kind, :reason, :added_at) "
        "ON CONFLICT (value) DO NOTHING",
        {"value": value, "kind": kind, "reason": reason, "added_at": now_utc()},
    )
    return result.rowcount == 1


def list_suppression(conn: Connection) -> list[RowMapping]:
    """The do-not-contact list, newest first."""
    return conn.execute(
        "SELECT value, kind, reason, added_at FROM suppression ORDER BY added_at DESC, value"
    ).fetchall()


def count_suppression(conn: Connection) -> int:
    row = conn.execute("SELECT COUNT(*) AS n FROM suppression").fetchone()
    return int(row["n"]) if row else 0


# --- sourcing progress --------------------------------------------------------------------------


def get_progress(conn: Connection, segment: str) -> RowMapping | None:
    return conn.execute(
        "SELECT * FROM sourcing_progress WHERE segment = :segment", {"segment": segment}
    ).fetchone()


def save_progress(
    conn: Connection,
    segment: str,
    filters_hash: str,
    next_page: int,
    total_entries: int | None,
    exhausted: bool,
) -> None:
    conn.execute(
        """
        INSERT INTO sourcing_progress
            (segment, filters_hash, next_page, total_entries, exhausted, updated_at)
        VALUES (:segment, :filters_hash, :next_page, :total_entries, :exhausted, :updated_at)
        ON CONFLICT (segment) DO UPDATE SET
            filters_hash = excluded.filters_hash,
            next_page = excluded.next_page,
            total_entries = excluded.total_entries,
            exhausted = excluded.exhausted,
            updated_at = excluded.updated_at
        """,
        {
            "segment": segment,
            "filters_hash": filters_hash,
            "next_page": next_page,
            "total_entries": total_entries,
            "exhausted": 1 if exhausted else 0,
            "updated_at": now_utc(),
        },
    )


# --- Clay batches -------------------------------------------------------------------------------


def _waiting_for_clay_sql(segment: str | None) -> tuple[str, dict[str, Any]]:
    where = "status = 'new' AND domain NOT IN (SELECT value FROM suppression)"
    params: dict[str, Any] = {}
    if segment:
        where += " AND segment = :segment"
        params["segment"] = segment
    return where, params


def count_waiting_for_clay(conn: Connection, segment: str | None = None) -> int:
    where, params = _waiting_for_clay_sql(segment)
    row = conn.execute(f"SELECT COUNT(*) AS n FROM companies WHERE {where}", params).fetchone()
    return int(row["n"]) if row else 0


def create_batch(conn: Connection, file: str, rows: int, segment: str | None) -> int:
    row = conn.execute(
        """
        INSERT INTO batches (file, rows, segment, exported_at)
        VALUES (:file, :rows, :segment, :exported_at)
        RETURNING id
        """,
        {"file": file, "rows": rows, "segment": segment, "exported_at": now_utc()},
    ).fetchone()
    assert row is not None
    return int(row["id"])


def update_batch(conn: Connection, batch_id: int, *, file: str, rows: int) -> None:
    conn.execute(
        "UPDATE batches SET file = :file, rows = :rows WHERE id = :id",
        {"file": file, "rows": rows, "id": batch_id},
    )


def delete_batch(conn: Connection, batch_id: int) -> None:
    conn.execute("DELETE FROM batches WHERE id = :id", {"id": batch_id})


def claim_companies_for_clay(
    conn: Connection, segment: str | None, limit: int, batch_id: int
) -> list[RowMapping]:
    """Claim up to `limit` waiting companies in one UPDATE ... RETURNING.

    Two concurrent exports never take the same company: each row can only move
    from status 'new' to 'exported' once.
    """
    where, params = _waiting_for_clay_sql(segment)
    return conn.execute(
        f"""
        UPDATE companies
        SET status = 'exported', batch_id = :batch_id
        WHERE id IN (SELECT id FROM companies WHERE {where} ORDER BY id LIMIT :limit)
          AND status = 'new'
        RETURNING *
        """,
        {**params, "batch_id": batch_id, "limit": limit},
    ).fetchall()


def get_batch(conn: Connection, batch_id: int) -> RowMapping | None:
    return conn.execute("SELECT * FROM batches WHERE id = :id", {"id": batch_id}).fetchone()


def finish_batch(
    conn: Connection, batch_id: int, account: str | None, credits: float | None
) -> None:
    """Record that Clay's results came back. Companies Clay returned nothing for become no_contact."""
    conn.execute(
        "UPDATE companies SET status = 'no_contact' WHERE batch_id = :batch_id AND status = 'exported'",
        {"batch_id": batch_id},
    )
    conn.execute(
        "UPDATE batches SET imported_at = :imported_at, "
        "clay_account = COALESCE(:account, clay_account), "
        "clay_credits = COALESCE(:credits, clay_credits) WHERE id = :batch_id",
        {
            "imported_at": now_utc(),
            "account": account,
            "credits": credits,
            "batch_id": batch_id,
        },
    )


def list_batches(conn: Connection) -> list[RowMapping]:
    """Every batch with what came back: people, emails, and each state."""
    return conn.execute(
        """
        SELECT b.id, b.segment, b.rows, b.exported_at, b.imported_at, b.clay_account,
               b.clay_credits, b.file,
               COUNT(l.id) AS people,
               COUNT(l.email) AS emails,
               COUNT(*) FILTER (WHERE l.state = 'verified') AS verified,
               COUNT(*) FILTER (WHERE l.state = 'needs_check') AS needs_check,
               COUNT(*) FILTER (WHERE l.state = 'hold') AS hold,
               COUNT(*) FILTER (WHERE l.state = 'dropped') AS dropped
        FROM batches b LEFT JOIN leads l ON l.batch_id = b.id
        GROUP BY b.id, b.segment, b.rows, b.exported_at, b.imported_at, b.clay_account,
                 b.clay_credits, b.file
        ORDER BY b.id DESC
        """
    ).fetchall()


