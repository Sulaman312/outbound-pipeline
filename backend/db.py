def _pk(dialect: str) -> str:
    """Auto-increment primary key that works on SQLite and Postgres."""
    if dialect == "postgresql":
        return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return "INTEGER PRIMARY KEY"


