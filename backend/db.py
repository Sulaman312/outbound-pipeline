def insert_lead(conn: Connection, lead: dict[str, Any]) -> bool:
    """Save a person. Returns False if we already have that email."""
    params = {column: lead.get(column) for column in LEAD_COLUMNS}
    stamp = now_utc()
    params["state_changed_at"] = stamp
    params["created_at"] = stamp
    columns = (*LEAD_COLUMNS, "state_changed_at", "created_at")
    placeholders = ", ".join(f":{c}" for c in columns)
    result = conn.execute(
        f"""
        INSERT INTO leads ({", ".join(columns)})
        VALUES ({placeholders})
        ON CONFLICT DO NOTHING
        """,
        params,
    )
    return result.rowcount == 1


def set_company_status(conn: Connection, company_id: int, status: str) -> None:
    """enriched always wins; no_contact never overwrites enriched."""
    if status == "enriched":
        conn.execute("UPDATE companies SET status = 'enriched' WHERE id = :id", {"id": company_id})
    else:
        conn.execute(
            "UPDATE companies SET status = :status WHERE id = :id AND status != 'enriched'",
            {"status": status, "id": company_id},
        )


def list_leads(conn: Connection, state: str | None = None) -> list[RowMapping]:
    """People found by Clay, with their company, newest first."""
    sql = """
        SELECT l.email, l.first_name, l.last_name, l.title, co.domain AS company_domain,
               co.name AS company_name, co.segment, l.state, l.state_reason, l.clay_status,
               l.linkedin_url, l.batch_id, l.created_at
        FROM leads l JOIN companies co ON co.id = l.company_id
    """
    params: dict[str, Any] = {}
    if state:
        sql += " WHERE l.state = :state"
        params["state"] = state
    return conn.execute(sql + " ORDER BY l.id DESC", params).fetchall()


def count_leads(conn: Connection) -> dict[str, int]:
    """Number of leads per state."""
    rows = conn.execute("SELECT state, COUNT(*) AS n FROM leads GROUP BY state").fetchall()
    return {str(row["state"]): int(row["n"]) for row in rows}


# --- backup -------------------------------------------------------------------------------------


def dump_all_tables(conn: Connection) -> dict[str, list[dict[str, Any]]]:
    """Every table as a list of plain dicts, for `outbound backup`."""
    out: dict[str, list[dict[str, Any]]] = {}
    for table in TABLES:
        if not _table_exists(conn, table):
            out[table] = []
            continue
        rows = conn.execute(f"SELECT * FROM {table} ORDER BY 1").fetchall()
        out[table] = [{key: _jsonable(value) for key, value in dict(row).items()} for row in rows]
    return out


def _jsonable(value: Any) -> Any:
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return str(value)
